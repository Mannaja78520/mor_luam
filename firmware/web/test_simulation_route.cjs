const assert = require('node:assert/strict');
const { SimulationWaypoints } = require('./js/32_simulation_route.js');
const { SimulationPlanner } = require('./js/45_simulation.js');
const original = [{ x: 1, y: 0 }];
const route = new SimulationWaypoints(original);
route.move(0, 0.3, -0.03);
assert.deepEqual(original, [{ x: 1, y: 0 }], 'editing a simulation never mutates the imported robot route');
assert.equal(route.add(51, 0).includes('50'), true);
assert.equal(route.points.length, 1, 'invalid coordinates leave the previous route intact');
route.add(0.5, 0.1); route.remove(0);
assert.deepEqual(route.points, [{ x: 0.5, y: 0.1, waitS: 0 }]);
route.replace(SimulationWaypoints.comparison(2, 7));
assert.equal(route.points.length, 7);
const p = { v: 0.03, w: 35, stop: 0.2, settle: 0.05 };
const start = { x: 0, y: 0, h: 0 };
const direct = SimulationPlanner.route(route.points, start, p, false);
const detour = SimulationPlanner.route(route.points, start, p, true);
assert.ok(detour.detours > 0 && detour.time < direct.time, 'the seven-leg local example actually compares different plans');
route.replace(SimulationWaypoints.comparison(0.3, 1));
assert.ok(route.points[0].y < 0, 'the CCW-only robot needs the example slightly to its RIGHT, not left');
assert.equal(SimulationPlanner.route(route.points, start, p, true).detours, 1);
route.clear(); assert.equal(route.points.length, 0);
assert.equal('api' in route, false, 'the simulation editor has no robot API client');
console.log('Simulation waypoint editor: local isolation, editing, examples and CCW direction PASS');
